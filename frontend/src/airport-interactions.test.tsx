import { act, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { expect, it, vi } from 'vitest'
import App from './App'
import { mockAirportCatalog, testAirportCatalog } from './test-airports'

const from = () => screen.getByRole('combobox', { name: 'From' })
const to = () => screen.getByRole('combobox', { name: 'To' })
const search = () => screen.getByRole('button', { name: 'Search awards' })
const chip = (code: string, side = 'departure') => screen.getByRole('button', { name: `Remove ${code} from ${side} airports` })
function setupPicker() {
  mockAirportCatalog()
  render(<App />)
  return userEvent.setup()
}
function finishTrip(cabins = ['Business']) {
  fireEvent.change(screen.getByLabelText('Departure date'), { target: { value: '2026-12-01' } })
  cabins.forEach((cabin) => fireEvent.click(screen.getByRole('checkbox', { name: cabin })))
}

it('loads only on form focus and preserves entries across failure and explicit retry', async () => {
  const user = userEvent.setup()
  let resolve!: (response: Response) => void
  vi.mocked(fetch).mockReturnValueOnce(new Promise((accept) => { resolve = accept }))
  mockAirportCatalog()
  render(<App />)
  const message = screen.getByRole('textbox', { name: 'Your trip request' })
  await user.click(message)
  fireEvent.change(message, { target: { value: 'Keep my note' } })
  expect(fetch).not.toHaveBeenCalled()
  await user.click(from())
  fireEvent.change(from(), { target: { value: 'New York' } })
  await user.click(to())
  fireEvent.change(to(), { target: { value: 'SEA' } })
  expect(fetch).toHaveBeenCalledExactlyOnceWith('/api/airports')
  expect(screen.getByText('Loading airport list…')).toBeVisible()
  expect(search()).toBeDisabled()
  fireEvent.submit(search().closest('form')!)
  expect(fetch).toHaveBeenCalledTimes(1)
  await act(async () => resolve(new Response(null, { status: 503 })))
  expect(screen.getByRole('alert')).toHaveTextContent('Your entries are retained')
  expect(from()).toHaveValue('New York')
  await user.click(from())
  expect(fetch).toHaveBeenCalledTimes(1)
  await user.click(screen.getByRole('button', { name: 'Retry airport list' }))
  expect(search()).toBeEnabled()
  await user.click(from())
  expect(within(screen.getByRole('dialog', { name: 'From airport selection' })).getAllByRole('checkbox')).toHaveLength(2)
  expect(screen.getByRole('dialog', { name: 'From airport selection' })).toHaveTextContent('John F. Kennedy International Airport')
  expect(to()).toHaveValue('SEA')
  expect(screen.getByRole('textbox', { name: 'Your trip request' })).toHaveValue('Keep my note')
  expect(vi.mocked(fetch).mock.calls.map(([url]) => url)).toEqual(['/api/airports', '/api/airports'])
})

it('requires explicit selections, retains chips across queries, and rejects overlapping endpoints', async () => {
  const user = setupPicker()
  await user.type(from(), 'JFK')
  await user.type(to(), 'SEA{Enter}')
  finishTrip()
  await user.click(search())
  expect(from()).toHaveAccessibleDescription('Choose at least one departure airport.')
  expect(from()).toHaveFocus()
  await user.click(screen.getByRole('checkbox', { name: /John F. Kennedy International Airport, JFK/ }))
  expect(chip('JFK')).toBeVisible()
  expect(from()).not.toHaveAttribute('aria-invalid', 'true')
  expect(from()).toHaveValue('')
  expect(from()).toHaveFocus()
  await user.type(from(), 'New Yor')
  expect(chip('JFK')).toBeVisible()
  await user.click(chip('JFK'))
  expect(from()).toHaveFocus()
  await user.click(search())
  expect(from()).toHaveAccessibleDescription('Choose at least one departure airport.')
  await user.clear(from())
  await user.type(from(), ' sea {Enter}')
  await user.click(search())
  expect(to()).toHaveAccessibleDescription('Departure and arrival airports must not overlap.')
  expect(fetch).toHaveBeenCalledTimes(1)
})

it.each(['mouse', 'touch'] as const)('selects airports across queries with %s, submits captured criteria, and resets', async (pointer) => {
  const user = setupPicker()
  const toggle = (target: HTMLElement) => pointer === 'mouse' ? user.click(target)
    : user.pointer([{ keys: '[TouchA>]', target }, { keys: '[/TouchA]' }])
  await user.type(from(), 'New York')
  const popup = screen.getByRole('dialog', { name: 'From airport selection' })
  const choices = within(popup).getAllByRole('checkbox')
  expect(choices.map((choice) => choice.getAttribute('aria-label'))).toEqual([
    expect.stringContaining('JFK'), expect.stringContaining('LGA'),
  ])
  expect(within(popup).queryByRole('group')).not.toBeInTheDocument()
  await toggle(within(popup).getByText('John F. Kennedy International Airport', { exact: true }))
  expect(from()).toHaveValue('')
  expect(from()).toHaveFocus()
  await user.type(from(), 'New York')
  await toggle(screen.getByRole('checkbox', { name: /LaGuardia Airport, LGA/ }))
  expect(chip('LGA')).toBeVisible()
  expect(from()).toHaveValue('')
  expect(from()).toHaveFocus()
  await toggle(within(popup).getByText('LaGuardia Airport', { exact: true }))
  expect(screen.queryByRole('checkbox', { name: /LaGuardia Airport, LGA/ })).not.toBeInTheDocument()
  expect(screen.queryByRole('button', { name: /Remove LGA/ })).not.toBeInTheDocument()
  expect(from()).toHaveFocus()
  await user.type(from(), 'Heathrow')
  await toggle(within(popup).getByText('LHR', { exact: true }))
  expect(chip('LHR').closest('li')).toHaveTextContent(/^LHR$/)
  expect(from()).toHaveValue('')
  expect(from()).toHaveFocus()
  await user.click(screen.getByRole('button', { name: 'Done' }))
  expect(from()).toHaveFocus()
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  await user.type(to(), 'SEA{Enter}LAX{Enter}HND')
  expect(chip('SEA', 'arrival')).toBeVisible()
  finishTrip(['Economy', 'Business'])
  vi.mocked(fetch).mockResolvedValueOnce(Response.json({ message: 'No cached seats match.', results: [] }))
  await user.click(search())
  expect(await screen.findByText('No cached seats match.')).toBeVisible()
  expect(vi.mocked(fetch).mock.calls.map(([url]) => url)).toEqual(['/api/airports', '/api/search'])
  expect(JSON.parse(vi.mocked(fetch).mock.calls[1][1]?.body as string)).toEqual({
    origin: ['JFK', 'LHR'], destination: ['SEA', 'LAX'], departure_date: '2026-12-01',
    passengers: 1, cabins: ['economy', 'business'],
  })
  const summary = screen.getByRole('region', { name: 'Current trip' })
  expect(summary).toHaveTextContent('JFK / LHR')
  expect(summary).toHaveTextContent('SEA / LAX')
  await user.click(screen.getByRole('button', { name: 'New trip' }))
  expect(from()).toHaveValue('')
  expect(to()).toHaveValue('')
  expect(screen.queryByRole('button', { name: /Remove .* airports/ })).not.toBeInTheDocument()
  await user.type(from(), 'JFK')
  expect(screen.getByRole('checkbox', { name: /John F. Kennedy International Airport, JFK/ })).not.toBeChecked()
  expect(fetch).toHaveBeenCalledTimes(2)
})

it('caps checkbox and exact-code additions, deduplicates codes, and removes chips', async () => {
  const user = setupPicker()
  await user.type(from(), 'SEA{Enter}LAX{Enter}ORD{Enter}LHR{Enter}HND{Enter}New York')
  await user.click(screen.getByRole('checkbox', { name: /John F. Kennedy International Airport, JFK/ }))
  const selected = screen.getByRole('list', { name: 'Selected departure airports' })
  expect(selected.children).toHaveLength(6)
  await user.type(from(), 'New York')
  const seventh = screen.getByRole('checkbox', { name: /LaGuardia Airport, LGA/ })
  await user.click(seventh)
  expect(screen.getByText('Choose up to 6 airports. Remove an airport before adding more.')).toBeVisible()
  expect(seventh).not.toBeChecked()
  expect(from()).toHaveValue('New York')
  await user.clear(from())
  await user.type(from(), 'JFK{Enter}GRU{Enter}')
  expect(selected.children).toHaveLength(6)
  expect(screen.queryByRole('button', { name: /Remove GRU/ })).not.toBeInTheDocument()
  expect(from()).toHaveValue('GRU')
  await user.keyboard('{Escape}')
  for (const code of ['SEA', 'LAX', 'ORD', 'LHR', 'HND', 'JFK']) await user.click(chip(code))
  expect(from()).toHaveFocus()
  expect(selected).toBeEmptyDOMElement()
  expect(fetch).toHaveBeenCalledTimes(1)
})

it('supports no-match feedback, composition, native checkbox navigation and Escape without searching', async () => {
  const user = setupPicker()
  await user.type(from(), 'No such airport')
  expect(screen.getByText('No matching airports.')).toBeVisible()
  await user.clear(from())
  await user.type(from(), 'sao')
  expect(screen.getByRole('checkbox', { name: /GRU, São Paulo/ })).toBeVisible()
  fireEvent.compositionStart(from())
  fireEvent.change(from(), { target: { value: 'JFK' } })
  expect(fireEvent.keyDown(from(), { key: 'Enter', isComposing: true })).toBe(false)
  fireEvent.compositionEnd(from())
  expect(fireEvent.keyDown(from(), { key: 'Enter', keyCode: 229 })).toBe(false)
  expect(screen.queryByRole('button', { name: /Remove .* airports/ })).not.toBeInTheDocument()
  await user.clear(from())
  for (const [query, code] of [['New York', 'JFK'], ['LGA', 'LGA']]) {
    await user.type(from(), query)
    const choice = screen.getByRole('checkbox', { name: new RegExp(`, ${code},`) })
    await user.tab()
    expect(screen.getByRole('button', { name: 'Done' })).toHaveFocus()
    await user.tab()
    expect(choice).toHaveFocus()
    await user.keyboard('{Enter}')
    expect(choice).not.toBeChecked()
    await user.keyboard(' ')
    expect(choice).toBeChecked()
    expect(from()).toHaveValue('')
    expect(from()).toHaveFocus()
  }
  await user.keyboard('{Escape}')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(from()).toHaveFocus()
  expect(chip('JFK')).toBeVisible()
  expect(chip('LGA')).toBeVisible()
  await user.tab()
  expect(to()).toHaveFocus()
  expect(fetch).toHaveBeenCalledTimes(1)
})

it('revalidates the exact date when the origin or origin-local day changes without changing the date', async () => {
  vi.setSystemTime(new Date('2026-11-11T01:00:00Z'))
  const user = setupPicker()
  await user.type(from(), 'SEA{Enter}')
  await user.type(to(), 'LHR{Enter}')
  const date = screen.getByLabelText('Departure date')
  fireEvent.change(date, { target: { value: '2026-11-10' } })
  await user.click(screen.getByRole('checkbox', { name: 'Economy' }))
  expect(date).toHaveAttribute('min', '2026-11-10')
  expect(date).toHaveAttribute('max', '2027-11-10')
  await user.click(screen.getByRole('button', { name: 'Remove SEA from departure airports' }))
  await user.type(from(), 'HND{Enter}')
  expect(date).toHaveValue('2026-11-10')
  expect(date).toHaveAttribute('min', '2026-11-11')
  await user.click(search())
  expect(date).toHaveAccessibleDescription(/today or later/)
  await user.click(screen.getByRole('button', { name: 'Remove HND from departure airports' }))
  await user.type(from(), 'SEA{Enter}')
  expect(date).not.toHaveAttribute('aria-invalid', 'true')
  vi.setSystemTime(new Date('2026-11-12T01:00:00Z'))
  await user.click(search())
  expect(date).toHaveAccessibleDescription(/today or later/)
  expect(date).toHaveValue('2026-11-10')
  expect(fetch).toHaveBeenCalledTimes(1)
})

